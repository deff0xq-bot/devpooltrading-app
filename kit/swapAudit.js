  function auditLadder(lib, plan, intent, nowS) {
    const no = (reason) => ({ reason });
    if (!plan || typeof plan !== "object" || plan.network !== T.MAINNET) return no("network");
    if (T.rawAddress(plan.from) !== intent.owner) return no("wallet");
    if (!Number.isInteger(plan.subwallet) || plan.subwallet < 1 || plan.subwallet > SUBWALLET_MAX) return no("subwallet");
    if (T.rawAddress(plan.orderWallet) !== intent.orderWallet || intent.orderWallet === intent.owner) return no("order_wallet");
    if (!(typeof intent.offer === "string" && intent.offer.startsWith("0:"))) return no("offer");
    if (!orderOffer(intent.offer)) return no("offer_unpinned");
    const validUntil = plan.validUntil;
    if (!Number.isInteger(validUntil) || validUntil < nowS + ORDER_VALID_MIN_S || validUntil > nowS + ORDER_VALID_MAX_S) return no("valid_until");
    if (!Number.isInteger(plan.seqno) || plan.seqno < 0) return no("seqno");
    const expected = T.parseUnits(plan.expectedOut);
    const side = plan.pool && T.parseUnits(plan.pool.tonSide);
    if (!expected || !side || expected * ORDER_POOL_DIVISOR > side) return no("size");
    if (!intent.stopOut && !intent.takeOut) return no("nothing");
    if (intent.stopOut && intent.stopOut >= expected) return no("stop_above_price");
    if (intent.takeOut && intent.takeOut <= expected) return no("take_below_price");
    const wantFloors = intent.stopOut ? ORDER_FLOORS.map((percent) => intent.stopOut * percent / 100n) : [];
    if (!Array.isArray(plan.stops) || plan.stops.length !== wantFloors.length) return no("ladder");
    if (intent.takeOut ? !plan.take : plan.take) return no("take");
    const seen = [];
    for (let i = 0; i < wantFloors.length; i++) seen.push(auditOrderMessage(lib, plan.stops[i], intent, wantFloors[i], validUntil));
    if (plan.take) seen.push(auditOrderMessage(lib, plan.take, intent, intent.takeOut, validUntil));
    const wrong = seen.find((one) => one.reason);
    if (wrong) return wrong;
    if (new Set(seen.map((one) => one.to)).size !== 1 || new Set(seen.map((one) => one.router)).size !== 1 || new Set(seen.map((one) => one.deadline)).size !== 1) return no("mixed");
    return { reason: null, seen, floors: seen.slice(0, wantFloors.length).map((one) => one.minOut), take: plan.take ? seen[seen.length - 1].minOut : null };
  }
